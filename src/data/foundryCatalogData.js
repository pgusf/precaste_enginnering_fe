// Helper that resolves any subcategory slug (falls back gracefully to the Manholes/Foundry assembly with a customized title so every link in your header works immediately)
export function getSubcategoryBySlug(subcategorySlug = "manholes") {
  const normalized = (subcategorySlug || "manholes").toLowerCase();
  if (FOUNDRY_SUBCATEGORIES[normalized]) {
    return FOUNDRY_SUBCATEGORIES[normalized];
  }

  // Format slug into human-readable title if user clicks another subcategory link
  const prettyTitle = normalized
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");

  return {
    ...FOUNDRY_SUBCATEGORIES.manholes,
    slug: normalized,
    title: `${prettyTitle} — 3D Assembly & Parts`,
  };
}